// Optional UI checks. Start app.py with a disposable database before running.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1365, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = process.env.TEST_URL || 'http://127.0.0.1:8000';
  let passed = 0;
  const pass = label => { passed++; console.log(`PASS: ${label}`); };
  try {
    await page.goto(base);
    await page.locator('#matches .card').first().waitFor();
    assert.equal(await page.locator('#matches .card').count(), 4);
    pass('Initial page loads four fictional partners');
    await page.locator('#profile-form [name=name]').fill('UI tester');
    await page.locator('#profile-form [name=activity]').selectOption('Running');
    await page.locator('#profile-form [name=slot]').selectOption('Weekend mornings');
    await page.locator('#profile-form [name=level]').selectOption('Intermediate');
    await page.locator('#profile-form [name=area]').selectOption('Downtown');
    await page.getByRole('button', { name: 'Save & find partners' }).click();
    await page.waitForFunction(() => document.querySelector('#matches h3')?.textContent === 'Sam (demo)');
    pass('Saving preferences reranks the partner cards');
    await page.locator('#match-filter').selectOption('schedule');
    assert.equal(await page.locator('#matches .card').count(), 1);
    pass('Availability filter narrows results');
    await page.getByText('Create a meetup', { exact: true }).click();
    await page.locator('#meetup-form [name=title]').fill('Browser test session');
    await page.locator('#meetup-form [name=location]').fill('Public lobby');
    const day = new Date(); day.setDate(day.getDate() + 7);
    await page.locator('#meetup-form [name=day]').fill(day.toISOString().slice(0,10));
    await page.locator('#meetup-form [name=time]').fill('18:00');
    await page.getByRole('button', { name: 'Create meetup', exact: true }).click();
    const session = page.locator('#events .card').filter({ hasText: 'Browser test session' }).last();
    await session.getByRole('button', { name: 'Leave meetup' }).waitFor();
    assert.match(await session.textContent(), /1\/4 attending/);
    pass('Creating a meetup displays it with its creator attending');
    await session.getByRole('button', { name: 'Leave meetup' }).click();
    await session.getByRole('button', { name: 'Join meetup' }).waitFor();
    await session.getByRole('button', { name: 'Join meetup' }).click();
    await session.getByRole('button', { name: 'Leave meetup' }).waitFor();
    pass('Leave and join buttons complete their flows');
    await page.locator('#interest-form [name=email]').fill('ui-test@example.com');
    await page.locator('#interest-form [name=consent]').check();
    await page.getByRole('button', { name: 'Record my interest' }).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Interest saved locally'));
    assert.match(await page.locator('#interest-count').textContent(), /1 unique/);
    pass('Interest form saves consented email and updates local count');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#profile-form [name=name]').value === 'UI tester');
    await session.getByRole('button', { name: 'Leave meetup' }).waitFor();
    pass('Profile and meetup persist after reload');
    await page.locator('#profile-form [name=name]').fill('<img src=x onerror=alert(1)>');
    await page.getByRole('button', { name: 'Save & find partners' }).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Profile saved'));
    assert.equal(await page.locator('img').count(), 0);
    pass('User text is handled without HTML injection');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    pass('Mobile viewport has no horizontal overflow');
    if (process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH, fullPage: true });
    assert.deepEqual(errors, []);
    pass('No browser JavaScript errors');
    console.log(`${passed}/${passed} browser checks passed`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
